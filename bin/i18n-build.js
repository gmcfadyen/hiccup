#!/usr/bin/env node
// bin/i18n-build.js — generate public/i18n/<lang>.js from locales/<lang>.json.
//
// Run after editing a translation file:  npm run i18n
//
// The catalogue is emitted as .js assigning a global, NOT as .json, because
// server.js's STATIC_TYPES whitelist has no '.json' entry — a /locales/fr.json
// fetch would 404 today. .js is already whitelisted and already served with
// Cache-Control: no-cache, so a rebuilt catalogue is live on the next load with
// zero server changes.
'use strict';

const fs = require('fs');
const path = require('path');
const i18n = require('../lib/i18n');

const inv = i18n.buildInventory();

fs.mkdirSync(i18n.CATALOGUE_DIR, { recursive: true });

for (const lang of i18n.LANGS) {
  const strings = lang === 'en' ? {} : i18n.buildCatalogue(lang, inv);
  const keys = Object.keys(strings).sort();
  const lines = keys.map((k) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(strings[k]));
  const body =
    '/* Generated by bin/i18n-build.js from locales/' + lang + '.json — do not edit.\n' +
    ' * Keys are hashes of the ENGLISH SOURCE STRING, so editing the English mints a\n' +
    ' * new key, the lookup misses, and the UI falls back to the new English rather\n' +
    ' * than showing a stale translation of text that no longer exists. */\n' +
    'window.HICCUP_I18N = {\n' +
    '  lang: ' + JSON.stringify(lang) + ',\n' +
    '  strings: {\n' + lines.join(',\n') + (lines.length ? '\n' : '') +
    '  }\n' +
    '};\n';
  fs.writeFileSync(i18n.catalogueFile(lang), body);
  console.log('i18n: public/i18n/' + lang + '.js — ' + keys.length + ' strings');
}

for (const line of i18n.summaryLines(i18n.audit(inv))) console.log('i18n: ' + line);

// Anything translated but no longer present in the tree is dead weight in the
// file a human maintains; name it rather than pruning silently, because the
// usual cause is an English edit that also needs the translation redone.
for (const lang of i18n.TARGET_LANGS) {
  const orphans = i18n.auditLang(lang, inv).orphans;
  if (!orphans.length) continue;
  console.log('i18n: ' + lang + ' has ' + orphans.length + ' orphaned entr' +
    (orphans.length === 1 ? 'y' : 'ies') + ' in locales/' + lang + '.json:');
  for (const o of orphans.slice(0, 20)) console.log('  - ' + JSON.stringify(o));
  if (orphans.length > 20) console.log('  … and ' + (orphans.length - 20) + ' more');
}

console.log('i18n: catalogues written to ' + path.relative(process.cwd(), i18n.CATALOGUE_DIR));
